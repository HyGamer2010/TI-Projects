def dr_sprite(dat, x, y):
    for rec in dat:
        d.set_color(*pal[rec >> 20 & 7])
        d.fill_rect(((rec >> 15) & 31) - 1 + x, ((rec >> 10) & 31) - 1 + y, (rec >> 5) & 31, rec & 31)

def dr_tile(x, y, init = False):
    ny = y - y_lvl + rel_pos[1]
    if(ny >= len(lvl)):
        return
    #inf == ((lvl[ny]) >> (c_shift - ((x - 1) * 3))) & 7
    if(velocity[0] == 0 and velocity[1] == 0 and not init):
        return
    else:
        inf = ((lvl[ny]) >> (c_shift - (x * 3))) & 7
        if(inf == 0):
            d.set_color(92, 148, 252)
            d.fill_rect(x * 20 - 1, y * 20 - 1, 21, 21)
        else:
            dr_sprite(sprs[inf], (x) * 20, (y) * 20)



def dr_perspec(init = False):
    #d.set_color(92, 148, 252)
    #d.fill_rect(-1, -1, 321, 211)
    global shifts
    shifts = [c_shift - (x * 3) for x in range(12)]
    for y in range(len(lvl) + y_lvl - rel_pos[1] - 1):
        for x in range(12):
            ny = y - y_lvl + rel_pos[1]
            if(ny >= len(lvl)):
                continue
            #inf == ((lvl[ny]) >> (c_shift - ((x - 1) * 3))) & 7
            if(velocity[0] == 0 and velocity[1] == 0 and not init):
                continue
            else:
                inf = ((lvl[ny]) >> shifts[x]) & 7
                if(inf == 0):
                    d.set_color(92, 148, 252)
                    d.fill_rect(x * 20 - 1, y * 20 - 1, 21, 21)
                else:
                    dr_sprite(sprs[inf], (x) * 20, (y) * 20)

def upd_rel(x, y):
    d.set_color(92, 148, 252)
    d.fill_rect(rel_pos[0] * 20 - 1, (9 - rel_pos[1]) * 20 - 1, 21, 21)
    rel_pos[0] = min(5, max(0, rel_pos[0] + x))
    
    dr_sprite(sprs[14], rel_pos[0] * 20, (9 - rel_pos[1]) * 20)
    dr_perspec()

def up_ents():
    for ent in ents:
        d.set_color(92, 148, 252)
        dr_tile(int(ent[2] - ((669 - c_shift) / 3)), int((ent[3] - rel_pos[1])), True)

        if(lvl[ent[3]] >> (669 - ((ent[2] + ent[1]) * 3)) & 3 != 0):
            ent[1] = -ent[1]
        if(velocity[0] != 0 or velocity[1] != 0):
            dr_tile(int(ent[2] - ((669 - c_shift) / 3) + velocity[0]), int((ent[3] - rel_pos[1]) + velocity[1]), True)
        ent[2] += ent[1]
        dr_sprite(sprs[ent[0]], (ent[2] - ((669 - c_shift) / 3)) * 20, ((ent[3] - rel_pos[1]) + y_lvl) * 20)
