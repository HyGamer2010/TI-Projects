upd_timer = 1
jmp_timer = 0
while True:
    key = s.get_key(0)
    upd_timer -= .02
    if(key != 0):
        #c_shift = min(669, max(0, c_shift - (3 if key == 26 else -3 if key == 24 else 0)))
        if(key == 26):
            if(rel_pos[0] < 5):
                upd_rel(1, 0)
                velocity[0] = 0
            else:
                c_shift = min(669, max(0, c_shift - 3))
                velocity[0] = 1
                up_ents()
                upd_timer = 1
                dr_perspec()
        elif(key == 24):
            velocity[0] = 0
            if(rel_pos[0] > 0):
                upd_rel(-1, 0)
        else:
            velocity[0] = 0
        if(key == 25):
            jmp_timer = 5
    if(upd_timer <= 0):
        up_ents()
        upd_timer = 1
    if(jmp_timer > 0):
        jmp_timer -= 1
        velocity[1] = 1
    elif(velocity[1] == 1):
        velocity[1] = -1
    if(velocity[1] != 0):
        #y_lvl -= velocity[1]
        if(((lvl[y_lvl + velocity[1]]) >> int((669 - c_shift) / 3 + velocity[0])) & 7 == 0):
            y_lvl += velocity[1]
